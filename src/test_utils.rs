#[cfg(test)]
mod tests {
    use std::io::{Read, Write};

    use super::*;

    #[test]
    fn given_queued_bytes_when_read_then_return_them_in_order() {
        let mut channel = MockChannel::new();
        channel.add_bytes(&[1, 2, 3]);

        let mut buf = [0; 2];
        assert_eq!(channel.read(&mut buf).unwrap(), 2);
        assert_eq!(buf, [1, 2]);
        assert_eq!(channel.read(&mut buf).unwrap(), 1);
        assert_eq!(buf[0], 3);
    }

    #[test]
    fn given_nothing_queued_when_read_then_time_out() {
        let mut channel = MockChannel::new();
        let err = channel.read(&mut [0; 1]).unwrap_err();
        assert_eq!(err.kind(), io::ErrorKind::TimedOut);
    }

    #[test]
    fn given_bytes_when_write_then_record_them() {
        let mut channel = MockChannel::new();
        channel.write_all(&[4, 5]).unwrap();
        assert_eq!(channel.write_buffer, vec![4, 5]);
    }
}
