//! Test doubles for code that talks to an SA430: an in-memory [`MockChannel`] and canned device responses.
//!
//! Only compiled for this crate's own tests, or for downstream crates that enable the `test-utils` feature.
//!
//! ```
//! use sa430::device::Sa430;
//! use sa430::frame::Command;
//! use sa430::test_utils::{an_ack_response, MockChannel};
//!
//! let mut channel = MockChannel::new();
//! channel.add_response(&an_ack_response(Command::BlinkLed));
//!
//! let mut device = Sa430::new(Box::new(channel));
//! device.blink().unwrap();
//! ```
use std::collections::VecDeque;
use std::io;

use crate::frame::{Command, Frame};

/// A channel that replays queued responses and records everything written to it.
///
/// Reading past the queued data fails with [`io::ErrorKind::TimedOut`], like a real serial port would.
#[derive(Debug, Default)]
pub struct MockChannel {
    read_buffer: VecDeque<u8>,
    /// Bytes written to the channel, in order.
    pub write_buffer: Vec<u8>,
}

impl MockChannel {
    /// Creates a channel with nothing queued.
    pub fn new() -> Self {
        Self::default()
    }

    /// Queues a frame to be read by the device under test.
    pub fn add_response(&mut self, frame: &Frame) {
        self.add_bytes(&frame.to_bytes());
    }

    /// Queues raw bytes to be read by the device under test.
    pub fn add_bytes(&mut self, bytes: &[u8]) {
        self.read_buffer.extend(bytes);
    }
}

impl io::Write for MockChannel {
    fn write(&mut self, buf: &[u8]) -> io::Result<usize> {
        self.write_buffer.extend_from_slice(buf);
        Ok(buf.len())
    }

    fn flush(&mut self) -> io::Result<()> {
        Ok(())
    }
}

impl io::Read for MockChannel {
    fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
        if self.read_buffer.is_empty() && !buf.is_empty() {
            return Err(io::Error::new(io::ErrorKind::TimedOut, "no more queued responses"));
        }
        let len = buf.len().min(self.read_buffer.len());
        for (dst, src) in buf.iter_mut().zip(self.read_buffer.drain(..len)) {
            *dst = src;
        }
        Ok(len)
    }
}

/// Acknowledge frame the device sends before executing `command`.
pub fn an_ack_response(command: Command) -> Frame {
    Frame::new(command)
}

/// Error frame carrying `code`.
pub fn an_error_response(code: u16) -> Frame {
    Frame::with_data(Command::GetLastError, &code.to_be_bytes()).unwrap()
}

/// Response to [`Command::GetIdn`].
pub fn a_get_idn_response() -> Frame {
    Frame::with_data(
        Command::GetIdn,
        b"Texas Instruments,MSP-SA430-SUB1GHZ: RF Dev Support Tool,HW2.0",
    )
    .unwrap()
}

/// Response to [`Command::GetSerialNumber`] (serial 2312).
pub fn a_get_serial_number_response() -> Frame {
    Frame::with_data(Command::GetSerialNumber, &0x0908u32.to_be_bytes()).unwrap()
}

/// Response to [`Command::GetCoreVersion`] (version 2.10).
pub fn a_get_core_version_response() -> Frame {
    Frame::with_data(Command::GetCoreVersion, &0x020Au16.to_be_bytes()).unwrap()
}

/// Response to [`Command::GetSpectrumVersion`] (version 2.5).
pub fn a_get_spectrum_version_response() -> Frame {
    Frame::with_data(Command::GetSpectrumVersion, &0x0205u16.to_be_bytes()).unwrap()
}

/// Data frame of a sweep ([`Command::GetSpecNoInit`]) carrying raw `samples` (at most 255).
pub fn a_spectrum_response(samples: &[i8]) -> Frame {
    let data: Vec<u8> = samples.iter().map(|&s| s as u8).collect();
    Frame::with_data(Command::GetSpecNoInit, &data).unwrap()
}

/// Response to [`Command::FlashRead`] carrying `data` (at most 255 bytes).
pub fn a_read_flash_response(data: &[u8]) -> Frame {
    Frame::with_data(Command::FlashRead, data).unwrap()
}

/// Queues the ACK + response pairs the device sends when its calibration is read.
pub fn add_calibration_responses(channel: &mut MockChannel) {
    for chunk in [
        PROG_HEADER_DATA,
        CALIBRATION_DATA_1,
        CALIBRATION_DATA_2,
        CALIBRATION_DATA_3,
        CALIBRATION_DATA_4,
        CALIBRATION_DATA_5,
        CALIBRATION_DATA_6,
        CALIBRATION_DATA_7,
    ] {
        channel.add_response(&an_ack_response(Command::FlashRead));
        channel.add_response(&a_read_flash_response(chunk));
    }
}

